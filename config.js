//  WHERE SHOULD FORM SUBMISSIONS GO?
//
//  Leave TRY_BACKEND_URL empty ("") and the website keeps using
//  FormSubmit, which emails each submission to
//  therealyou0806@gmail.com (the behaviour the site has today).
//
//  To save submissions into your own DATABASE instead:
//  1. Run the backend in the "backend" folder (see README.md),
//     locally or online (e.g. on Render).
//  2. Put its address between the quotes below, for example:
//       window.TRY_BACKEND_URL = "http://localhost:4000";
//     or, when the backend is online:
//       window.TRY_BACKEND_URL = "https://try-backend-oabw.onrender.com";
//  3. Save this file. Every form on the site (Join, Show Interest,
//     Contact, Newsletter) will then save into the database, and
//     you can read the submissions in the backend's Admin page.
//
//  Do NOT put a "/" at the end of the address.
// ============================================================

window.TRY_BACKEND_URL = "https://try-backend-oabw.onrender.com";
